/// ゲーム開始時のカレンダー初期データ
pub fn カレンダー初期化(カレンダー: &mut カレンダーストア) {
    カレンダー.追記(ゲーム日付::new(4, 1), "新学期はじまり", false);
    カレンダー.追記(ゲーム日付::new(4, 3), "祠の水替え", false);
    カレンダー.追記(ゲーム日付::new(4, 5), "浜辺の清掃（当番）", false);
    カレンダー.追記(ゲーム日付::new(4, 7), "おばあちゃんのお見舞い", false);
    カレンダー.追記(ゲーム日付::new(4, 10), "春祭り準備", false);
    カレンダー.追記(ゲーム日付::new(4, 12), "春祭り", true);
    カレンダー.追記(ゲーム日付::new(4, 15), "▼▼▼▼▼", true);
    カレンダー.追記(ゲーム日付::new(4, 20), "「選定」", true);
    カレンダー.追記(ゲーム日付::new(4, 25), "――――", true);
    カレンダー.追記(ゲーム日付::new(4, 30), "わたしは", true);
}

/// 初期エリア登録
pub fn エリア初期化(エリア: &mut エリアストア) {
    エリア.追加("浜辺",   Vec3::new(15.0, 6.0, 20.0), 10.0);
    エリア.追加("村はずれ", Vec3::new(0.0, 8.0, 0.0),  15.0);
    エリア.追加("祠の前",  Vec3::new(-10.0, 8.0, -15.0), 6.0);
    エリア.追加("丘の上",  Vec3::new(8.0, 25.0, 8.0), 8.0);
}

